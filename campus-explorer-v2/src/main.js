// 1. 创建 Pinia 实例并注册到 Vue
// ============================================================
const pinia = createPinia()

const app = createApp(App)
app.use(pinia)
app.use(router)

// ============================================================
// 2. 预置测试账号（在 mount 之前完成，确保组件渲染时数据就绪）
//    测试账号：张三 / 123456, 李四 / 123456
//    密码使用 SHA-256 哈希存储，和正常注册逻辑一致
//    仅首次运行写入，已有数据则跳过
// ============================================================
const authStore = useAuthStore()
authStore.initTestAccounts()

// ============================================================
// 3. 挂载应用
// ============================================================
app.mount('#app')
